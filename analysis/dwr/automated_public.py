DISTRIBUTION_CONTRACT = "dwr-automated-distribution/1.0.0"


def is_automated(entry):
    return entry.get("data_contract") == automated.PROFILE_B_CONTRACT


def payload_files(document, edition_id):
    """Regenerate an exact allowlist, never copy a private candidate directory."""
    automated.validate(document)
    if document["contract"] != automated.PROFILE_B_CONTRACT:
        raise DwrError("automated_public_contract_refused")
    window = window_from_strings(document["window"]["start_inclusive"], document["window"]["end_exclusive"])
    if window.edition_id(1) != edition_id:
        raise DwrError("automated_public_edition_mismatch")
    files = automated_render.files(document)
    # These reports describe the private preparation. Current presentation is
    # generated by the site/README adapter from the same canonical document.
    for name in ("report.en.html", "report.fr.html", "catalog.json", "manifest.json"):
        del files[name]
    dates = [r["date_utc"] for r in document["tables"]["coverage"] if r["observation_status"] == "observed"]
    catalog = {"schema_version": DISTRIBUTION_CONTRACT, "edition_id": edition_id,
               "data_contract": document["contract"], "canonical_document": "projection.json",
               "schema": "schema.json", "manifest": "manifest.json", "figures": "figures.json",
               "dates": {"period_start_inclusive": str(window.start),
                         "period_end_exclusive": str(window.end_exclusive),
                         "latest_available_data_date": max(dates) if dates else None},
               "tables": {key: {"path": name, "columns": list(automated.table_fields(document["contract"])[key])}
                          for key, name in automated.filenames(document["contract"]).items()},
               "operational_state_source": "../../../config/editions.json",
               "preparation_metadata": "projection.json preserves the unapproved local preparation state; it is not the current availability or review registry",
               "distribution_scope": "selected automated aggregates; no on-demand counts, daily family margins or private diagnostics"}
    files["catalog.json"] = canonical_json(catalog).encode("utf-8")
    files["manifest.json"] = canonical_json({"schema_version": DISTRIBUTION_CONTRACT,
        "edition_id": edition_id, "canonical_document": "projection.json",
        "operational_state_source": "../../../config/editions.json",
        "files": {name: sha256_bytes(value) for name, value in sorted(files.items())},
        "self_excluded": "manifest.json"}).encode("utf-8")
    return files


def document(root, edition_id):
    doc = load_json(root / "data/editions" / edition_id / "projection.json")
    automated.validate(doc)
    if doc["contract"] != automated.PROFILE_B_CONTRACT:
        raise DwrError("automated_public_contract_refused")
    return doc


def verify_payload(root, edition_id):
    from . import distribution
    distribution.check_sources(root)
    directory = root / "data/editions" / edition_id
    doc = document(root, edition_id)
    files = payload_files(doc, edition_id)
    distribution.check_output(directory, files)
    return {"edition_id": edition_id, "contract": doc["contract"], "files": len(files),
            "metrics": doc["metrics"], "reproduction": "exact_public_projection_bytes"}


