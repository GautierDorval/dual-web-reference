"""A small, safe Markdown renderer for the repository's own documents.

Supported: headings, paragraphs, lists, tables, blockquotes, fenced code, inline
code, links, bold, backslash escapes. All text is HTML-escaped; the only raw HTML
let through is the `<picture>` figure block generated by render (attributes are
re-escaped) and generated-block comments, which are dropped. Links are passed
through `rewrite_link` so that repository paths map to site pages.
"""

from __future__ import annotations

import html
import re

INLINE_CODE = re.compile(r"`([^`]+)`")
LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")
BOLD = re.compile(r"\*\*(.+?)\*\*")
ESCAPED = re.compile(r"\\([\\`*_\[\]<>|#])")
PICTURE = re.compile(r'^<picture><source media="\(max-width: 640px\)" srcset="([^"<>]+)"><img src="([^"<>]+)" alt="([^"<>]*)" width="960"></picture>$')
SAFE_URL = re.compile(r"^(https://|http://|\.{0,2}/|[A-Za-z0-9._-]+(/|\.|#|$))")


def _inline(text: str, rewrite) -> str:
    placeholders = []

    def keep(fragment: str) -> str:
        placeholders.append(fragment)
        return f"\x00{len(placeholders) - 1}\x00"

    text = ESCAPED.sub(lambda m: keep(html.escape(m.group(1))), text)
    text = INLINE_CODE.sub(lambda m: keep(f"<code>{html.escape(m.group(1))}</code>"), text)

    def link(match):
        label, url = match.group(1), match.group(2)
        target = rewrite(url) if SAFE_URL.match(url) and not url.lower().startswith("javascript:") else None
        inner = _inline(label, rewrite)
        if not target:
            return keep(inner)
        external = target.startswith(("http://", "https://"))
        rel = ' rel="noopener noreferrer"' if external else ""
        return keep(f'<a href="{html.escape(target, quote=True)}"{rel}>{inner}</a>')

    text = LINK.sub(link, text)
    text = html.escape(text, quote=False)
    text = BOLD.sub(r"<strong>\1</strong>", text)
    return re.sub("\x00(\\d+)\x00", lambda m: placeholders[int(m.group(1))], text)


def _row(line: str) -> list[str]:
    cells, current, escaped = [], "", False
    body = line.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|") and not body.endswith("\\|"):
        body = body[:-1]
    for char in body:
        if escaped:
            current += "\\" + char
            escaped = False
        elif char == "\\":
            escaped = True
        elif char == "|":
            cells.append(current.strip())
            current = ""
        else:
            current += char
    cells.append(current.strip())
    return cells


def render(markdown: str, rewrite=lambda url: url) -> str:
    lines = markdown.replace("\r\n", "\n").split("\n")
    out, index = [], 0
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()
        if not stripped or stripped.startswith("<!-- dwr:"):
            index += 1
            continue
        if stripped.startswith("```"):
            index += 1
            block = []
            while index < len(lines) and not lines[index].strip().startswith("```"):
                block.append(lines[index])
                index += 1
            index += 1
            out.append(f"<pre><code>{html.escape(chr(10).join(block))}</code></pre>")
            continue
        heading = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        if heading:
            level = len(heading.group(1))
            text = heading.group(2)
            anchor = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
            out.append(f'<h{level} id="{anchor}">{_inline(text, rewrite)}</h{level}>')
            index += 1
            continue
        picture = PICTURE.match(stripped)
        if picture:
            compact, wide, alt = (rewrite(picture.group(1)), rewrite(picture.group(2)), picture.group(3))
            out.append(f'<figure><picture><source media="(max-width: 640px)" srcset="{html.escape(compact, quote=True)}">'
                       f'<img src="{html.escape(wide, quote=True)}" alt="{html.escape(html.unescape(alt), quote=True)}" '
                       f'loading="lazy" width="960"></picture></figure>')
            index += 1
            continue
        if stripped.startswith("|") and index + 1 < len(lines) and re.match(r"^\|?\s*:?-{3,}", lines[index + 1].strip()):
            header = _row(stripped)
            aligns = ["right" if cell.strip().endswith(":") else "left" for cell in _row(lines[index + 1])]
            index += 2
            body = []
            while index < len(lines) and lines[index].strip().startswith("|"):
                body.append(_row(lines[index]))
                index += 1
            head = "".join(f'<th scope="col">{_inline(cell, rewrite)}</th>' for cell in header)
            rows = "".join("<tr>" + "".join(
                f'<td class="{"num" if aligns[i] == "right" else ""}">{_inline(cell, rewrite)}</td>'
                for i, cell in enumerate(row)) + "</tr>" for row in body)
            out.append(f'<div class="table-wrap"><table><thead><tr>{head}</tr></thead><tbody>{rows}</tbody></table></div>')
            continue
        if stripped.startswith(">"):
            block = []
            while index < len(lines) and lines[index].strip().startswith(">"):
                block.append(lines[index].strip()[1:].strip())
                index += 1
            out.append(f"<blockquote><p>{_inline(' '.join(block), rewrite)}</p></blockquote>")
            continue
        if re.match(r"^(-|\*|\d+\.)\s+", stripped):
            ordered = bool(re.match(r"^\d+\.", stripped))
            items = []
            while index < len(lines) and re.match(r"^\s*(-|\*|\d+\.)\s+", lines[index]):
                item = re.sub(r"^\s*(-|\*|\d+\.)\s+", "", lines[index])
                index += 1
                while index < len(lines) and lines[index].startswith("  ") and lines[index].strip() and not re.match(r"^\s*(-|\*|\d+\.)\s+", lines[index]):
                    item += " " + lines[index].strip()
                    index += 1
                items.append(f"<li>{_inline(item, rewrite)}</li>")
            tag = "ol" if ordered else "ul"
            out.append(f"<{tag}>{''.join(items)}</{tag}>")
            continue
        paragraph = [stripped]
        index += 1
        while index < len(lines) and lines[index].strip() and not re.match(r"^(#{1,6}\s|\||>|```|-\s|\*\s|\d+\.\s|<picture>|<!-- dwr:)", lines[index].strip()):
            paragraph.append(lines[index].strip())
            index += 1
        out.append(f"<p>{_inline(' '.join(paragraph), rewrite)}</p>")
    return "\n".join(out)
